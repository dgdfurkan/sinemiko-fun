import math
def oval(cx, cy, a, b, tilt, t0=0, t1=360, n=40):
    t = np.radians(np.linspace(t0, t1, n)); c, s_ = math.cos(math.radians(tilt)), math.sin(math.radians(tilt))
    x, y = b * np.cos(t), a * np.sin(t)
    return np.stack([cx + x * c - y * s_, cy + x * s_ + y * c], 1)
